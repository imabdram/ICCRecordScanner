import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const BASE = 'http://localhost:8080', P = 'DemoPass!2026';
mkdirSync('screenshots', { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 950 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String(e)));
p.on('console', m => m.type() === 'error' && errs.push(m.text()));
async function login(page, email) {
  await page.goto(BASE, { waitUntil: 'networkidle' });
  await page.waitForSelector('input[type=email]', { timeout: 20000 });
  await page.fill('input[type=email]', email);
  await page.fill('input[type=password]', P);
  await page.click('button[type=submit]', { force: true });
  await page.waitForSelector('.sidebar', { timeout: 30000 });
  await page.waitForTimeout(2200);
}
await p.goto(BASE, { waitUntil: 'networkidle' });
await p.waitForTimeout(800);
await p.screenshot({ path: 'screenshots/01-login.png' });
await login(p, 'admin@sim.example.com');
await p.screenshot({ path: 'screenshots/02-admin-dashboard.png', fullPage: true });
await p.click('button[data-view=records]', { force: true });
await p.waitForTimeout(1800);
await p.screenshot({ path: 'screenshots/03-records.png', fullPage: true });
await p.click('button[data-view=users]', { force: true });
await p.waitForTimeout(1800);
await p.screenshot({ path: 'screenshots/04-users.png', fullPage: true });
const mctx = await b.newContext({ viewport: { width: 420, height: 900 } });
const m = await mctx.newPage();
await login(m, 'admin@sim.example.com');
await m.screenshot({ path: 'screenshots/05-mobile-dashboard.png', fullPage: true });
await m.click('.menu-btn', { force: true });
await m.waitForTimeout(500);
await m.screenshot({ path: 'screenshots/06-mobile-drawer.png' });
console.log('errors:', errs.join(' | ') || 'none');
await b.close();