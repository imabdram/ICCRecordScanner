"""Renders phone-style mockups of the planned app, before any Flutter code is written.

Not a screenshot: a layout drawing, so the UI can be approved first.
ASCII-only strings on purpose -- this file is regenerated by tooling and must not
depend on console encoding.
"""
from PIL import Image, ImageDraw, ImageFont
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "app-mockup.png")

W, H = 380, 780
PAD = 40
BG = (244, 246, 248)
RED = (225, 25, 41)
INK = (16, 28, 43)
MUTED = (110, 122, 138)
LINE = (226, 230, 235)
WHITE = (255, 255, 255)
DARK = (12, 14, 18)
TEAL = (38, 166, 154)
GREEN = (52, 168, 83)
AMBER = (240, 173, 78)


def font(size, bold=False):
    for name in (("segoeuib.ttf" if bold else "segoeui.ttf"),
                 ("arialbd.ttf" if bold else "arial.ttf")):
        path = os.path.join(r"C:\Windows\Fonts", name)
        if os.path.exists(path):
            try:
                return ImageFont.truetype(path, size)
            except Exception:
                pass
    return ImageFont.load_default()


F_TITLE = font(23, True)
F_H = font(17, True)
F_BODY = font(13)
F_SMALL = font(11)
F_TINY = font(10)
F_BTN = font(14, True)


def rounded(d, box, r, fill=None, outline=None, width=1):
    d.rounded_rectangle(box, radius=r, fill=fill, outline=outline, width=width)


def label(d, xy, text, f, fill=INK, anchor="la"):
    d.text(xy, text, font=f, fill=fill, anchor=anchor)


def icon(d, name, cx, cy, size=16, color=INK, width=2):
    """Vector icons, so nothing depends on the font having a glyph."""
    s = size / 2.0
    if name == "menu":
        for i in (-1, 0, 1):
            d.line((cx - s, cy + i * size / 3.2, cx + s, cy + i * size / 3.2), fill=color, width=width)
    elif name == "flash":
        d.polygon([(cx + s * 0.25, cy - s), (cx - s * 0.55, cy + s * 0.1),
                   (cx - s * 0.05, cy + s * 0.1), (cx - s * 0.25, cy + s),
                   (cx + s * 0.6, cy - s * 0.15), (cx + s * 0.05, cy - s * 0.15)], fill=color)
    elif name == "search":
        r = s * 0.6
        d.ellipse((cx - r - 2, cy - r - 2, cx + r - 2, cy + r - 2), outline=color, width=width)
        d.line((cx + r - 2, cy + r - 2, cx + s, cy + s), fill=color, width=width)
    elif name == "list":
        for i in (-1, 0, 1):
            y = cy + i * size / 3.2
            d.line((cx - s + 3, y, cx + s, y), fill=color, width=width)
            d.ellipse((cx - s - 1, y - 1.4, cx - s + 1.4, y + 1.4), fill=color)
    elif name == "scan":
        a = s * 0.8
        for sx, sy in ((-1, -1), (1, -1), (-1, 1), (1, 1)):
            d.line((cx + sx * a, cy + sy * a, cx + sx * a - sx * a * 0.55, cy + sy * a), fill=color, width=width)
            d.line((cx + sx * a, cy + sy * a, cx + sx * a, cy + sy * a - sy * a * 0.55), fill=color, width=width)
        d.line((cx - a * 0.4, cy, cx + a * 0.4, cy), fill=color, width=width)
    elif name == "gear":
        d.ellipse((cx - s * 0.5, cy - s * 0.5, cx + s * 0.5, cy + s * 0.5), outline=color, width=width)
        d.ellipse((cx - 1.8, cy - 1.8, cx + 1.8, cy + 1.8), fill=color)
    elif name == "sync":
        d.arc((cx - s, cy - s, cx + s, cy + s), 30, 320, fill=color, width=width)
    elif name == "logout":
        d.line((cx - s, cy - s, cx - s, cy + s), fill=color, width=width)
        d.line((cx - s, cy, cx + s, cy), fill=color, width=width)
        d.line((cx + s * 0.25, cy - s * 0.5, cx + s, cy), fill=color, width=width)
        d.line((cx + s * 0.25, cy + s * 0.5, cx + s, cy), fill=color, width=width)
    elif name == "download":
        d.line((cx, cy - s, cx, cy + s * 0.35), fill=color, width=width)
        d.line((cx - s * 0.5, cy - s * 0.15, cx, cy + s * 0.4), fill=color, width=width)
        d.line((cx + s * 0.5, cy - s * 0.15, cx, cy + s * 0.4), fill=color, width=width)
        d.line((cx - s, cy + s, cx + s, cy + s), fill=color, width=width)


def phone_shell(d, x, y, title):
    rounded(d, (x, y, x + W, y + H), 30, fill=WHITE, outline=(210, 216, 224), width=2)
    rounded(d, (x + W // 2 - 42, y + 10, x + W // 2 + 42, y + 22), 6, fill=(232, 236, 241))
    label(d, (x + W / 2, y + H + 16), title, F_SMALL, MUTED, anchor="ma")
    return (x, y + 30, x + W, y + H)


def status_bar(d, x0, y0, dark=False):
    c = (200, 205, 212) if dark else (120, 130, 145)
    label(d, (x0 + 18, y0 + 8), "9:41", F_TINY, c)
    label(d, (x0 + W - 18, y0 + 8), "100%", F_TINY, c, anchor="ra")


def bottom_nav(d, x0, y1, active):
    h = 58
    top = y1 - h
    d.rectangle((x0, top, x0 + W, y1), fill=WHITE)
    d.line((x0, top, x0 + W, top), fill=LINE, width=1)
    items = [("scan", "Scan"), ("list", "Records")]
    third = W / len(items)
    for i, (glyph, name) in enumerate(items):
        cx = x0 + third * i + third / 2
        on = i == active
        col = RED if on else MUTED
        icon(d, glyph, cx, top + 20, 17, col, 2)
        label(d, (cx, top + 34), name, F_TINY, col, anchor="ma")


def draw_login(img, x, y):
    d = ImageDraw.Draw(img)
    x0, y0, x1, y1 = phone_shell(d, x, y, "1 - Login (once)")
    status_bar(d, x0, y0)

    cy = y0 + 110
    rounded(d, (x0 + W / 2 - 34, cy, x0 + W / 2 + 34, cy + 68), 18, fill=RED)
    icon(d, "list", x0 + W / 2, cy + 34, 30, WHITE, 3)
    label(d, (x0 + W / 2, cy + 92), "ICC Record Scanner", F_TITLE, INK, anchor="ma")
    label(d, (x0 + W / 2, cy + 120), "Sign in to start recording", F_SMALL, MUTED, anchor="ma")

    def field(top, caption, value, is_secret=False):
        label(d, (x0 + 28, top), caption, F_TINY, MUTED)
        rounded(d, (x0 + 28, top + 16, x1 - 28, top + 58), 10,
                fill=(248, 249, 251), outline=LINE)
        label(d, (x0 + 42, top + 31), value, F_BODY, MUTED if not is_secret else INK)
        return top + 74

    fy = cy + 160
    fy = field(fy, "USERNAME", "your.username")
    fy = field(fy, "PASSWORD", "********", is_secret=True)

    rounded(d, (x0 + 28, fy + 8, x1 - 28, fy + 54), 12, fill=RED)
    label(d, (x0 + W / 2, fy + 22), "Sign in", F_BTN, WHITE, anchor="ma")
    label(d, (x0 + W / 2, fy + 76), "Accounts are created by your team leader.",
          F_TINY, MUTED, anchor="ma")


def draw_scanner(img, x, y):
    d = ImageDraw.Draw(img)
    x0, y0, x1, y1 = phone_shell(d, x, y, "2 - Scan (default tab)")
    d.rectangle((x0, y0, x1, y1), fill=DARK)
    status_bar(d, x0, y0, dark=True)

    for cx, glyph in ((x0 + 34, "menu"),):
        d.ellipse((cx - 18, y0 + 34, cx + 18, y0 + 70), fill=(40, 44, 52))
        icon(d, glyph, cx, y0 + 52, 16, WHITE, 2)

    wx, wy = x0 + 34, y0 + 210
    ww, wh = W - 68, 132
    rounded(d, (wx, wy, wx + ww, wy + wh), 16, outline=(90, 96, 106), width=2)
    for cx, cy, dx, dy in ((wx, wy, 1, 1), (wx + ww, wy, -1, 1),
                           (wx, wy + wh, 1, -1), (wx + ww, wy + wh, -1, -1)):
        d.line((cx, cy, cx + 26 * dx, cy), fill=TEAL, width=5)
        d.line((cx, cy, cx, cy + 26 * dy), fill=TEAL, width=5)
    d.line((wx + 14, wy + wh / 2, wx + ww - 14, wy + wh / 2), fill=TEAL, width=2)

    label(d, (x0 + W / 2, wy + wh + 26), "Align the ICCID inside the frame",
          F_SMALL, (200, 205, 212), anchor="ma")

    # Flashlight: white rectangle, bottom centre, above the tab bar.
    fx, fy = x0 + W / 2, y1 - 116
    bw, bh = 190, 54
    rounded(d, (fx - bw / 2, fy - bh / 2, fx + bw / 2, fy + bh / 2), 14, fill=WHITE)
    icon(d, "flash", fx - 52, fy, 20, INK, 2)
    label(d, (fx - 34, fy - 8), "Flashlight", F_BTN, INK)

    bottom_nav(d, x0, y1, 0)


def draw_entry(img, x, y):
    """The form shown after a scan (and for manual entry)."""
    d = ImageDraw.Draw(img)
    x0, y0, x1, y1 = phone_shell(d, x, y, "3 - After scan / manual entry")
    d.rectangle((x0, y0, x1, y1), fill=BG)
    status_bar(d, x0, y0)

    d.rectangle((x0, y0 + 24, x1, y0 + 88), fill=WHITE)
    icon(d, "menu", x0 + 34, y0 + 56, 16, INK)
    label(d, (x0 + 58, y0 + 44), "New record", F_H, INK)

    def field(top, caption, value, locked=False, hint=None, icon_name=None):
        label(d, (x0 + 22, top), caption, F_TINY, MUTED)
        bg = (238, 240, 244) if locked else WHITE
        rounded(d, (x0 + 22, top + 16, x1 - 22, top + 58), 10, fill=bg, outline=LINE)
        label(d, (x0 + 36, top + 31), value, F_BODY, MUTED if locked else INK)
        if locked:
            label(d, (x1 - 30, top + 31), "locked", F_TINY, (170, 176, 186), anchor="ra")
        if icon_name:
            icon(d, icon_name, x1 - 40, top + 37, 16, MUTED)
        if hint:
            label(d, (x0 + 22, top + 62), hint, F_TINY, MUTED)
            return top + 84
        return top + 72

    fy = y0 + 108
    fy = field(fy, "ICCID", "89252637990000001234", hint="Edit it, or tap the icon to scan again", icon_name="scan")
    fy = field(fy, "CUSTOMER NAME", "Hodan Ali")
    fy = field(fy, "PRIMARY NUMBER", "615555001")
    fy = field(fy, "BACKUP NUMBER", "615555002")

    rounded(d, (x0 + 22, fy + 6, x1 - 22, fy + 52), 12, fill=RED)
    label(d, (x0 + W / 2, fy + 20), "Save record", F_BTN, WHITE, anchor="ma")

    rounded(d, (x0 + 22, fy + 64, x1 - 22, fy + 106), 12, fill=WHITE, outline=LINE)
    label(d, (x0 + W / 2, fy + 78), "Save and scan another", F_SMALL, INK, anchor="ma")

    label(d, (x0 + W / 2, y1 - 34), "Saved offline first, uploaded when online",
          F_TINY, MUTED, anchor="ma")


