    label(d, (x0 + 88, y0 + 52), "Hodan Ali", F_H, INK)
    label(d, (x0 + 88, y0 + 76), "Sales Rep | hodan.ali", F_TINY, MUTED)

    by = y0 + 118
    rounded(d, (x0 + 18, by, x0 + panel_w - 18, by + 132), 12, fill=(248, 249, 251))
    pairs = [
        ("Zone", "Zone 2"),
        ("Region", "Bari Region"),
        ("Outlet", "Customer care Bosaso"),
        ("Team leader", "Abdi Hassan"),
    ]
    py = by + 14
    for k, v in pairs:
        label(d, (x0 + 32, py), k, F_TINY, MUTED)
        label(d, (x0 + 112, py), v, F_SMALL, INK)
        py += 28

